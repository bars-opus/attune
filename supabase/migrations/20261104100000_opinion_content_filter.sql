CREATE OR REPLACE FUNCTION private.match_form(p_text text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = ''
AS $fn$
-- match.between_ascii_letters folded, the base form, match.west_african
-- folded, NFD, match.strip_marks dropped, NFC, base.confusables again (a
-- look-alike that carried a mark), match.leet folded, match.separators to
-- a space, spaces collapsed and trimmed. Idempotent: a stored term is its
-- own match form.
DECLARE
  v text;
BEGIN
  IF p_text IS NULL THEN
    RETURN NULL;
  END IF;
  v := p_text;
  -- match.between_ascii_letters: ! and | with an ASCII letter on both sides
  IF v ~ '[\u0021\u007C]' THEN
    v := pg_catalog.regexp_replace(v, '(?<=[ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz])\u0021(?=[ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz])', 'i', 'g');
    v := pg_catalog.regexp_replace(v, '(?<=[ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz])\u007C(?=[ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz])', 'l', 'g');
  END IF;
  v := private.normalize_for_filter(v);
  -- match.west_african (one to one), then its multi entry
  IF v ~ '[\u014B\u0192\u0199\u01B4\u0253-\u0254\u0256-\u0257\u025B\u0263\u028B\u1E63\u1EB9\u1ECD]' THEN
    v := pg_catalog.replace(pg_catalog.translate(v,
      U&'\025B\0254\0192\028B\0253\0257\0199\0256\0263\01B4\1EB9\1ECD\1E63', 'eofvbdkdgyeos'),
      U&'\014B', 'ng');
  END IF;
  -- match.strip_marks (400 code points), between NFD and NFC
  v := pg_catalog.normalize(v, 'NFD');
  v := pg_catalog.regexp_replace(v,
