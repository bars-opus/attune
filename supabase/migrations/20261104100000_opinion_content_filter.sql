-- The poll writer's options (plan P-7): create_poll_for_post's own count
-- and length refusals first, so no scan runs on more than 4 options of 60
-- characters (batch-2 review I-4); then each option. Off: nothing.
CREATE OR REPLACE FUNCTION private.assert_poll_options_ok(p_options text[])
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
BEGIN
  IF p_options IS NULL OR NOT private.spec1_flag_on('opinions_safety_v1') THEN
    RETURN;
  END IF;
  IF (SELECT count(*) FROM pg_catalog.unnest(p_options) AS o WHERE pg_catalog.btrim(o) <> '') > 4 THEN
    RAISE EXCEPTION 'poll_option_count' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.unnest(p_options) AS o WHERE pg_catalog.char_length(pg_catalog.btrim(o)) > 60) THEN
    RAISE EXCEPTION 'poll_option_too_long' USING ERRCODE = '22023';
  END IF;
  PERFORM private.assert_part_content_ok(pg_catalog.btrim(o), 'poll_option')
     FROM pg_catalog.unnest(p_options) AS o
    WHERE pg_catalog.btrim(o) <> '';
END;
$fn$;

