-- Spec 1 W9a, migration 16 (spec §4.7 #16): the shared normaliser and the
-- pre-post content filter for Opinions.
--   * private.normalize_for_filter(text): the BASE form (spec §4.3 W9a,
--     review I-17): NFKC, lower case (Unicode simple case mapping, the
--     pg_c_utf8 collation, so every database folds alike), invisible,
--     bidi, filler, variation-selector and tag characters removed,
--     Cyrillic, Greek, Armenian and small-capital look-alikes (and o-slash,
--     l-stroke) folded to Latin, every other-script decimal digit to 0-9,
--     separators (whitespace, ASCII and common Unicode punctuation, U+2800)
--     to single spaces, then NFC. The Unicode 16 characters whose fold
--     differs between PostgreSQL 17 and V8 are pinned first (compat pins),
--     so the two ports agree on every code point.
--     Letters and their marks stay as typed (e-open, o-open and eng stay)
--     and $ + , . / : @ _ are kept, so contact details and amounts keep
--     their meaning.
--   * private.match_form(text): ! and | between ASCII letters read as i
--     and l, then the base form plus the West African letter fold,
--     combining marks dropped (NFD, the combining-diacritic blocks, the
--     Cyrillic, Hebrew and Arabic marks, NFC), the look-alike fold again, the leetspeak fold,
--     then the kept punctuation and < = > to spaces. Idempotent. Filter
--     terms are stored and matched in this form.
--   * Both were first generated by script from (this file is now the
--     source of truth: it also holds hand-written helpers, e.g. the
--     quoted_text / poll_option refusal HINTs; never regenerate it)
--     supabase/functions/_shared/unicode_fold_table.json version
--     2026-11-04.5 (sha256 of the sorted ASCII JSON
--     ad2d6e6a469f240c7b80d6317c7889134ab06454cdd0a34f01aae41dcb69a54c;
--     the TypeScript port _shared/unicode_normaliser.ts reads the same
--     file). opinion_filter_contracts.sql checks every entry, all the
--     shared goldens and idempotence; opinion_filter_parity_contracts.sql
