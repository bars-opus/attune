-- ---------------------------------------------------------------------
-- Digit words (spec §4.3 W9a): English zero..nine, "oh" next to a digit,
-- and the reviewed local number words. Digit words next to each other are
-- joined into one group, so "zero two four four ..." reads as 0244...
-- Takes the base form.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.digits_from_words(p_text text)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_tokens text[];
  v_digit text[];
  v_out text := '';
  v_prev_word boolean := false;
  v_dev boolean;
  v_local_words boolean;
  v_n int;
  i int;
BEGIN
  IF p_text IS NULL OR p_text = '' THEN
    RETURN p_text;
  END IF;
  v_dev := private.attune_environment() = 'development';
  -- One look first: with no active number word that can match here, no
  -- token is looked up (plan PF-C11).
  v_local_words := EXISTS (
    SELECT 1 FROM private.content_filter_terms AS t
     WHERE t.family = 'number_word' AND t.active AND (t.source = 'reviewed' OR v_dev));
  v_tokens := pg_catalog.string_to_array(p_text, ' ');
  v_n := pg_catalog.array_length(v_tokens, 1);
  v_digit := pg_catalog.array_fill(NULL::text, ARRAY[v_n]);
  FOR i IN 1 .. v_n LOOP
    v_digit[i] := CASE v_tokens[i]
                    WHEN 'zero' THEN '0' WHEN 'one' THEN '1' WHEN 'two' THEN '2'
                    WHEN 'three' THEN '3' WHEN 'four' THEN '4' WHEN 'five' THEN '5'
                    WHEN 'six' THEN '6' WHEN 'seven' THEN '7' WHEN 'eight' THEN '8'
                    WHEN 'nine' THEN '9'
                  END;
  END LOOP;
  -- The local number words: one lookup over the distinct tokens that are
  -- not English digit words (batch-2 review I-5), not one per token.
  IF v_local_words THEN
    SELECT pg_catalog.array_agg(coalesce(e.d, w.digit) ORDER BY e.i) INTO v_digit
      FROM ROWS FROM (pg_catalog.unnest(v_digit), pg_catalog.unnest(v_tokens)) WITH ORDINALITY AS e(d, tok, i)
      LEFT JOIN (
        SELECT x.tok,
               (SELECT t.digit
                  FROM private.content_filter_terms AS t
                 WHERE t.family = 'number_word' AND t.active
                   AND (t.source = 'reviewed' OR v_dev)
                   AND t.term = x.mtok
                 ORDER BY t.id
                 LIMIT 1) AS digit
          -- OFFSET 0 keeps each subquery a fence: match_form runs once per
          -- distinct token and the lookup once per distinct token.
          -- A token of plain a-z letters is its own match form.
          FROM (SELECT y.tok, CASE WHEN y.tok ~ '^[abcdefghijklmnopqrstuvwxyz]+$' THEN y.tok
                                   ELSE private.match_form(y.tok) END AS mtok
                  FROM (SELECT DISTINCT u.tok
                          FROM ROWS FROM (pg_catalog.unnest(v_digit), pg_catalog.unnest(v_tokens)) AS u(d, tok)
                         WHERE u.d IS NULL) AS y
                OFFSET 0) AS x
        OFFSET 0
      ) AS w ON w.tok = e.tok;
  END IF;
  -- "oh" / "o" only inside a run: next to a digit word or a numeral.
  FOR i IN 1 .. v_n LOOP
    IF v_digit[i] IS NULL AND v_tokens[i] IN ('oh', 'o')
       AND ((i > 1 AND (v_digit[i - 1] IS NOT NULL OR v_tokens[i - 1] ~ '^[0-9]+$'))
         OR (i < v_n AND (v_digit[i + 1] IS NOT NULL OR v_tokens[i + 1] ~ '^[0-9]+$'))) THEN
      v_digit[i] := '0';
    END IF;
  END LOOP;
  FOR i IN 1 .. v_n LOOP
    IF v_digit[i] IS NOT NULL THEN
      v_out := v_out || CASE WHEN v_prev_word THEN '' WHEN i = 1 THEN '' ELSE ' ' END || v_digit[i];
      v_prev_word := true;
    ELSE
      v_out := v_out || CASE WHEN i = 1 THEN '' ELSE ' ' END || v_tokens[i];
      v_prev_word := false;
    END IF;
  END LOOP;
  RETURN v_out;
END;
$fn$;

-- ---------------------------------------------------------------------
-- Number shapes that are never phone numbers (batch-2 review I-1): dates
-- (d/m/y or y/m/d with . / or -), times (h.mm, h:mm, hhmm with h) and
-- score pairs (1-2 digits, a dash, 1-2 digits, not in a longer chain),
-- each to " n ". Contact branch only, on the NFKC lower-case text, before
-- the base form turns "-" into a space.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.mask_number_shapes(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = ''
AS $fn$
  SELECT pg_catalog.regexp_replace(
    pg_catalog.regexp_replace(
      pg_catalog.regexp_replace(p_text,
        -- dates
        '(?<![0-9./-])((0?[1-9]|[12][0-9]|3[01])[./-](0?[1-9]|1[0-2])[./-]((19|20)[0-9]{2}|[0-9]{2})|(19|20)[0-9]{2}[./-](0?[1-9]|1[0-2])[./-](0?[1-9]|[12][0-9]|3[01]))(?![0-9]|[./-][0-9])',
        ' n ', 'g'),
      -- times
      '(?<![0-9./:-])([01]?[0-9]|2[0-3])[.:h][0-5][0-9](?![0-9]|[./:-][0-9])',
      ' n ', 'g'),
    -- score pairs (hyphen, en dash, em dash)
    '(?<![0-9./-])[0-9]{1,2} ?[\u002D\u2013\u2014] ?[0-9]{1,2}(?![0-9]|[./-]?[0-9])',
    ' n ', 'g');
$fn$;

-- ---------------------------------------------------------------------
-- Contact details (spec §4.3 W9a), on the base form after digit words.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.has_contact_info(p_text text)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $fn$
DECLARE
  m text[];
  v_groups text[];
  v_digits text;
  v_lens int[];
  v_n int;
  g text;
  v_years boolean;
  v_thousands boolean;
BEGIN
  IF p_text IS NULL OR p_text = '' THEN
    RETURN false;
  END IF;

  -- Phone numbers: a run of 9-15 digits joined by at most single
  -- separators (the base form has already turned - ( ) into spaces).
  -- Known v0 gaps, accepted (plan PF-C5; recorded at the W9a gate). Not
  -- read as contact details: a run with no + padded past 15 digits
  -- (call 0244123456 99999999); digits split by the kept , _ : or by a
  -- letter or emoji (024,412,3456, 024x412x3456, 024<emoji>412<emoji>3456);
  -- letters for digits (O244l23456); dingbat digits; a number typed in
  -- score or date shape (0-2 4-4 1-2 3-4 5-6); bare domains outside the
  -- ending list (kofi.de, kofi.app); a platform name with no ":" or "@"
  -- (kofi99 on insta, snap kofi99). Closed: a + run of any length from 9
  -- digits. The filter is a floor; reports and the reviewed lists back
  -- it up.
  FOR m IN SELECT pg_catalog.regexp_matches(p_text, '(\+ ?)?([0-9]+(?:[ ./][0-9]+)*)', 'g') LOOP
    v_groups := pg_catalog.regexp_split_to_array(m[2], '[ ./]');
    v_digits := pg_catalog.array_to_string(v_groups, '');
    v_n := char_length(v_digits);
    CONTINUE WHEN v_n < 9;
    -- Years: "1999 2004 2010".
    v_years := true;
    FOREACH g IN ARRAY v_groups LOOP
      IF g !~ '^(19|20)[0-9]{2}$' THEN v_years := false; END IF;
    END LOOP;
    CONTINUE WHEN v_years;
    IF m[1] IS NOT NULL THEN
      RETURN true;                                   -- +233 ..., + 44 ...
    END IF;
    -- Without a +, a phone number is 9-15 digits.
    CONTINUE WHEN v_n > 15;
    -- Amounts grouped in thousands: "250 000 000".
    v_thousands := pg_catalog.array_length(v_groups, 1) >= 3 AND v_groups[1] ~ '^[1-9][0-9]{0,2}$';
    IF v_thousands THEN
      FOR i IN 2 .. pg_catalog.array_length(v_groups, 1) LOOP
        IF v_groups[i] !~ '^[0-9]{3}$' THEN v_thousands := false; END IF;
      END LOOP;
    END IF;
    CONTINUE WHEN v_thousands;
    IF v_digits ~ '^0' THEN
      RETURN true;                                   -- 024..., 00233...
    END IF;
    SELECT pg_catalog.array_agg(char_length(x) ORDER BY o) INTO v_lens
      FROM pg_catalog.unnest(v_groups) WITH ORDINALITY AS u(x, o);
    IF (v_lens = ARRAY[3, 3, 4] OR v_lens = ARRAY[10]) AND v_digits ~ '^[2-9][0-9]{2}[2-9]' THEN
      RETURN true;                                   -- NANP (415) 555-0132
    END IF;
    IF (v_lens = ARRAY[1, 3, 3, 4] OR v_lens = ARRAY[11]) AND v_digits ~ '^1[2-9][0-9]{2}[2-9]' THEN
      RETURN true;                                   -- NANP with its 1
    END IF;
    -- Every group after the first has 2+ digits, so a count or a list of
    -- scores (1 2 3 ... 10, 1-0 2-1 3-3) is not a number (plan PF-C4).
    -- The calling code is the whole first group (233 24 412 3456, 44 7911
    -- 123456, 233 244 12 34 56), or the number is one unbroken run
    -- (233244123456); no later group is a single digit; and some later
    -- group has 3+ digits. So counts, score and number lists and price
    -- lists (1200 1500 1800, 10 20 30 40 50 100) are not numbers
    -- (batch-2 review I-1, re-review N-2).
    IF v_n >= 11
       AND ((pg_catalog.array_length(v_groups, 1) = 1 AND v_digits ~ '^(233|234|44|27|254|255|256|225|237|221|229|228|226|231|232|220|353|49|33|31|91|971|966|86|1)')
         OR (v_groups[1] ~ '^(233|234|44|27|254|255|256|225|237|221|229|228|226|231|232|220|353|49|33|31|91|971|966|86|1)$'
             AND NOT (1 = ANY (v_lens[2:]))
             AND (SELECT pg_catalog.max(x) FROM pg_catalog.unnest(v_lens[2:]) AS x) >= 3)) THEN
      RETURN true;                                   -- a calling code, no +
    END IF;
  END LOOP;

  RETURN
    -- E-mail addresses, and "at ... dot ..." for common providers.
    p_text ~ '[a-z0-9._+]+@[a-z0-9]+(\.[a-z0-9]+)*\.[a-z]{2,}'
    OR p_text ~ '\m[a-z0-9._]+ ?(@|\mat\M) ?(gmail|googlemail|yahoo|ymail|hotmail|outlook|live|msn|icloud|aol|proton|protonmail|gmx|zoho|yandex) ?(\.|\mdot\M) ?(com|net|org|co|me|ch|uk|de|fr|gh|ng)\M'
    -- Links: schemes, www., WhatsApp and Telegram links, short-link
    -- hosts, bare domains on a fixed list of endings (plan P-7).
    OR p_text ~ '\mhttps?:/'
    OR p_text ~ '\mwww\.[a-z0-9]'
    OR p_text ~ '\m(wa|t)\.me\M'
    OR p_text ~ '\m(bit\.ly|tinyurl\.com|t\.co|goo\.gl|ow\.ly|is\.gd|buff\.ly|cutt\.ly|rb\.gy|shorturl\.at|tiny\.cc|linktr\.ee)\M'
    OR p_text ~ '\m[a-z0-9]+\.(com|net|org|info|biz|io|xyz|ly|gh|ng|uk)\M'
    -- @handles of three or more characters, not @everyone, @all, @here,
    -- @admin or @mods (forum talk; review M-4), and not "@" read as "at"
    -- before a time ("@5pm", "@10am", "@7p.m.", "dinner @5pm."; W9 final
    -- I-1). The time must end the token, so "@5pmkofi", "@1pm.kofi" and
    -- "@10am10" stay handles. "@home", "@church" and "@work" cannot be told
    -- from a handle and stay refused (a known v0 gap, owner checklist 4).
    OR p_text ~ '(^|[^a-z0-9._@])@(?!(everyone|all|here|admin|mods)([^a-z0-9._]|$))(?![0-9]{1,2}([:.][0-9]{2})? ?([ap]\.?m)?\.?([^a-z0-9._]|$))[a-z0-9._]{3,}'
    -- A platform name, then ":" or "@", then a handle; "ig: @5pm" too (the
    -- time exemption above never spares a handle after a platform name; W9
    -- final re-review N-2).
    OR p_text ~ '\m(instagram|insta|ig|snapchat|tiktok|telegram|tg|whatsapp|twitter|facebook|fb) ?[:@] ?@? ?[a-z0-9._]{3,}'
    -- Platform names that are also English words ("red flag signal:
    -- jealousy", "oh snap: forgot"): "@", or ":" and a handle-like token
    -- with a letter, 3+ characters and a digit, _ or an inner dot (plan
    -- PF-C4).
    OR p_text ~ '\m(snap|signal|threads) ?(@ ?[a-z0-9._]{3,}|: ?@ ?[a-z0-9._]{3,}|: ?(?=[a-z0-9._]{3})(?=[a-z0-9._]*[a-z])[a-z0-9._]*([0-9_]|\.[a-z0-9]))';
END;
$fn$;

-- ---------------------------------------------------------------------
-- The verdict (spec §4.3 W9a): NULL, or the first hit of contact_info,
-- slur, explicit, among p_families (NULL = all three). Spec 2 calls this
-- for prompts.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.content_filter_verdict(p_text text, p_families text[])
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_families constant text[] := coalesce(p_families, ARRAY['contact_info', 'slur', 'explicit']);
  v_base text;
  v_match text;
  v_squashed text;
  v_dev boolean;
  v_family text;
BEGIN
  IF p_text IS NULL OR btrim(p_text) = '' THEN
    RETURN NULL;
  END IF;
  -- Contact branch: U+3002, U+FF61 and U+06D4 read as "." (review M-3),
  -- then the number-shape mask (review I-1), then the base form.
  v_base := private.normalize_for_filter(private.mask_number_shapes(
    pg_catalog.lower(pg_catalog.normalize(
      pg_catalog.translate(p_text, U&'\3002\FF61\06D4', '...'), 'NFKC') COLLATE "pg_c_utf8")));
  IF 'contact_info' = ANY (v_families) AND private.has_contact_info(private.digits_from_words(v_base)) THEN
    RETURN 'contact_info';
  END IF;
  v_match := ' ' || private.match_form(p_text) || ' ';
  v_squashed := replace(v_match, ' ', '');
  v_dev := private.attune_environment() = 'development';
  FOREACH v_family IN ARRAY ARRAY['slur', 'explicit'] LOOP
    CONTINUE WHEN NOT (v_family = ANY (v_families));
    IF EXISTS (
      SELECT 1
        FROM private.content_filter_terms AS t
       WHERE t.family = v_family
         AND t.active
         AND (t.source = 'reviewed' OR v_dev)
         AND (strpos(v_match, ' ' || t.term || ' ') > 0
              OR (t.match_mode = 'squashed' AND strpos(v_squashed, replace(t.term, ' ', '')) > 0))
    ) THEN
      RETURN v_family;
    END IF;
  END LOOP;
  RETURN NULL;
END;
$fn$;

-- opinions_safety_v1 on: a verdict refuses the post with content:{verdict}.
-- Off (or unreadable): nothing is checked.
CREATE OR REPLACE FUNCTION private.assert_opinion_content_ok(p_text text)
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_verdict text;
BEGIN
  IF p_text IS NULL OR NOT private.spec1_flag_on('opinions_safety_v1') THEN
    RETURN;
  END IF;
  -- The writers' own limit, before any scan (batch-2 review I-4).
  IF pg_catalog.char_length(p_text) > 5000 THEN
    RAISE EXCEPTION 'invalid_content' USING ERRCODE = '22023';
  END IF;
  v_verdict := private.content_filter_verdict(p_text, ARRAY['contact_info', 'slur', 'explicit']);
  IF v_verdict IS NOT NULL THEN
    RAISE EXCEPTION 'content:%', v_verdict USING ERRCODE = '22023';
  END IF;
END;
$fn$;

